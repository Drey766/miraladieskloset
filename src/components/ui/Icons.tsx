/** Pick an icon for a "design benefit" title like "cushioning", "grip", "fitting comfort". */
export function FeatureIcon({ title, className }: { title: string; className?: string }) {
  const t = title.toLowerCase();
  if (/cushion|shock/.test(t)) return <LayersIcon className={className} />;
  if (/grip|traction|tread/.test(t)) return <TreadIcon className={className} />;
  if (/precision|control|feel/.test(t)) return <TargetIcon className={className} />;
  if (/light|weight/.test(t)) return <FeatherIcon className={className} />;
  if (/support|robust|abrasion|durab|resist|stab/.test(t)) return <ShieldIcon className={className} />;
  if (/breath|ventil/.test(t)) return <WindIcon className={className} />;
  if (/motion|energy|flex|freedom|return/.test(t)) return <ActivityIcon className={className} />;
  if (/comfort|anatom|fit|dressing/.test(t)) return <SmileIcon className={className} />;
  return <BoltIcon className={className} />;
}
